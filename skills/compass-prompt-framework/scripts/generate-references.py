#!/usr/bin/env python3
"""Generate the CoMPaSS section extracts from the packaged research paper.

Usage: python3 scripts/generate-references.py [--check]
Exit status: 0 up to date (or written), 1 stale or missing outputs with --check,
2 the paper could not be parsed.

Every extract is verbatim: headings are re-levelled to fit the new file, but no
prose, table, or example is edited. Inline citations such as \\[27\\] point to
the paper's "Sources" list, so each extract ends with the sources it cites and
stays readable on its own. Python 3.9+ standard library only; the script writes
only the generated files listed in OUTPUTS and performs no network access.
"""

import argparse
import re
import sys
from pathlib import Path

SKILL_ROOT = Path(__file__).resolve().parent.parent
PAPER = SKILL_ROOT / "references" / "compass-paper.md"
CUSTOM_EXAMPLE = SKILL_ROOT / "assets" / "examples" / "example-4-custom.md"
PAPER_TITLE = "# CoMPaSS: An Analysis-First Prompting Technique for Large Language Models"
GENERATED_NOTE = (
    "<!-- Generated by scripts/generate-references.py from references/compass-paper.md. "
    "Do not edit by hand: change the generator and run it again. -->"
)
HEADING = re.compile(r"^(#{1,6})\s+(.+?)\s*$")
FENCE = re.compile(r"^\s{0,3}(`{3,}|~{3,})")
CITATION = re.compile(r"\\\[(\d+)\\\]")
SOURCE = re.compile(r"^(\d+)\.\s+\[(.+)\]\((\S+)\)\s*$")


class PaperError(Exception):
    """The paper does not have the structure the extracts depend on."""


def paper_body(text):
    """Return the verbatim paper, without the packaging revision note."""
    start = text.find(PAPER_TITLE)
    if start < 0:
        raise PaperError("paper title not found: " + PAPER_TITLE)
    return text[start:]


def iter_lines(text):
    """Yield (line, in_fence) so headings inside code examples are left alone."""
    marker = None
    for line in text.splitlines():
        match = FENCE.match(line)
        if match:
            fence = match.group(1)
            if marker is None:
                marker = fence
                yield line, True
                continue
            if fence[0] == marker[0] and len(fence) >= len(marker) and not line.strip()[len(fence):]:
                marker = None
                yield line, True
                continue
        yield line, marker is not None


def extract_section(paper_text, heading_prefix):
    """Extract the section whose heading text starts with heading_prefix.

    The section ends at the next heading of the same or a higher level, or at a
    horizontal rule that separates top-level paper sections.
    """
    lines = list(iter_lines(paper_text))
    start = level = None
    for index, (line, fenced) in enumerate(lines):
        match = None if fenced else HEADING.match(line)
        if match and match.group(2).startswith(heading_prefix):
            start, level = index, len(match.group(1))
            break
    if start is None:
        raise PaperError("section not found: " + heading_prefix)
    end = len(lines)
    for index in range(start + 1, len(lines)):
        line, fenced = lines[index]
        if fenced:
            continue
        match = HEADING.match(line)
        if (match and len(match.group(1)) <= level) or line.strip() == "---":
            end = index
            break
    return "\n".join(line for line, _ in lines[start:end]).strip("\n")


def relevel(text, top_level):
    """Shift heading levels outside code fences so the first heading is top_level."""
    shift = None
    out = []
    for line, fenced in iter_lines(text):
        match = None if fenced else HEADING.match(line)
        if match:
            level = len(match.group(1))
            if shift is None:
                shift = top_level - level
            line = "#" * max(1, min(6, level + shift)) + " " + match.group(2)
        out.append(line)
    return "\n".join(out)


def parse_sources(paper_text):
    """Map citation numbers to (title, url) from the paper's Sources list."""
    try:
        block = paper_text.split("\n## Sources\n", 1)[1]
    except IndexError:
        raise PaperError("'## Sources' list not found") from None
    sources = {}
    for line in block.splitlines():
        match = SOURCE.match(line)
        if match:
            sources[int(match.group(1))] = (match.group(2), match.group(3))
    if not sources:
        raise PaperError("'## Sources' list is empty")
    return sources


def cited_sources(text, sources):
    """Render the Sources entries cited in text, in numeric order."""
    numbers = sorted({int(number) for number in CITATION.findall(text)})
    if not numbers:
        return ""
    missing = [number for number in numbers if number not in sources]
    if missing:
        raise PaperError("citations without a Sources entry: " + ", ".join(map(str, missing)))
    lines = ["", "## Sources cited in this extract", "",
             "Numbers match the inline citations above and the paper's Sources list.", ""]
    for number in numbers:
        title, url = sources[number]
        lines.append("- \\[{}\\] [{}]({})".format(number, title, url))
    return "\n".join(lines)


def document(title, intro, body, sources, footer=""):
    parts = [GENERATED_NOTE, "", "# " + title, "", intro, "", body.strip("\n")]
    cited = cited_sources(body, sources)
    if cited:
        parts.append(cited)
    if footer:
        parts.extend(["", footer.strip("\n")])
    return "\n".join(parts).rstrip("\n") + "\n"


def paper_link(section, prefix):
    return "[the CoMPaSS paper]({}compass-paper.md), Section {}".format(prefix, section)


EXAMPLES = (
    ("example-1-announcement.md", "Example 1"),
    ("example-2-decision.md", "Example 2"),
    ("example-3-agentic.md", "Example 3"),
)


def build(paper_raw):
    """Return {relative path: content} for every generated file."""
    paper = paper_body(paper_raw)
    sources = parse_sources(paper)
    outputs = {}

    outputs["references/literature-summary.md"] = document(
        "Literature summary",
        "> Verbatim extract of Sections 2.1–2.7 from {}. These are the verified findings "
        "CoMPaSS's inclusion rules rely on. Citations are preserved, not summarized further."
        .format(paper_link(2, "")),
        relevel(extract_section(paper, "2. Background and literature summary"), 2),
        sources,
    )
    outputs["references/vs-frameworks.md"] = document(
        "Positioning versus other frameworks",
        "> Verbatim extract of {}: the comparison with ART, RTF, CO-STAR, RISEN, CRISPE, the "
        "3 C's and context engineering, what CoMPaSS adds, and when a simpler framework is "
        "the better choice. CoMPaSS is untested, so this is positioning, not a ranking."
        .format(paper_link(8, "")),
        relevel(extract_section(paper, "8. Positioning relative to existing frameworks"), 2),
        sources,
    )
    outputs["references/limitations.md"] = document(
        "Limitations and trade-offs",
        "> Verbatim extract of {}. Read it before relying on CoMPaSS for a consequential "
        "prompt: it lists what the technique costs and what it does not do."
        .format(paper_link("9.1", "")),
        relevel(extract_section(paper, "9.1 Limitations and trade-offs"), 2),
        sources,
    )
    outputs["references/evaluation-plan.md"] = document(
        "Evaluation plan (pre-registered)",
        "> Exact copy of {}. Nothing in this skill reports results from this plan; it has "
        "not been run.".format(paper_link("9.2", "")),
        relevel(extract_section(paper, "9.2 Proposed evaluation plan"), 2),
        sources,
        footer=(
            "---\n\n"
            "## Contribute a run\n\n"
            "*This section is added by the skill package; it is not part of the paper.*\n\n"
            "External teams are invited to run this plan exactly as written and contribute the "
            "results. [`scripts/evaluate-skill.ts`](../scripts/evaluate-skill.ts) validates a "
            "task suite and a results file against this plan and computes its metrics; it does "
            "not call any model. The contribution process and data format are in the "
            "repository's [evaluation guide]"
            "(https://github.com/YourAKShaw/CoMPaSS-prompt-framework/blob/main/docs/EVALUATION.md)."
        ),
    )

    examples = extract_section(paper, "7. Worked examples")
    paper_examples = []
    for filename, prefix in EXAMPLES:
        section = extract_section(examples, prefix + ":")
        paper_examples.append(section)
        outputs["assets/examples/" + filename] = document(
            relevel(section, 1).splitlines()[0][2:],
            "> Verbatim from {} (Proposal; illustrative, not test results).".format(
                paper_link(7, "../../references/")),
            "\n".join(relevel(section, 1).splitlines()[1:]),
            sources,
        )
    counter = extract_section(examples, "Example 4 (counter-example)")

    if not CUSTOM_EXAMPLE.is_file():
        raise PaperError("custom example not found: " + str(CUSTOM_EXAMPLE))
    custom = CUSTOM_EXAMPLE.read_text(encoding="utf-8")
    counter_body = "\n".join(relevel(counter, 2).splitlines()[1:])
    worked = "\n\n".join([
        "| Example | Task type | Tier | o | a |\n"
        "|---|---|---|---|---|\n"
        "| [1](#example-1-communication-task-optional-components-omitted) | Communication | 1 | Omitted | Omitted |\n"
        "| [2](#example-2-analytical--decision-task-includes-o-omits-a) | Analysis / decision | 1 | Included | Omitted |\n"
        "| [3](#example-3-agentic-coding--multi-step-task-full-architecture-o-and-a-included) | Agentic coding | 2 | Included | Included |\n"
        "| [4](#example-4-go-to-market-brief-custom-includes-a-omits-o) | Go-to-market brief (custom) | 1 | Omitted | Included |\n"
        "| [Counter-example](#counter-example-when-not-to-use-compass) | Factual lookup | 0 | — | — |",
        *(relevel(section, 2) for section in paper_examples),
        relevel(custom, 2),
        "## Counter-example: when not to use CoMPaSS\n\n"
        "*The paper numbers this \"Example 4 (counter-example)\"; it is renamed here so it does "
        "not collide with the custom Example 4.*\n" + counter_body,
    ])
    outputs["references/worked-examples.md"] = document(
        "Worked examples",
        "> Examples 1–3 and the counter-example are verbatim from {} (Proposal; illustrative, "
        "not test results). Example 4 is the skill's custom example, copied from "
        "[`assets/examples/example-4-custom.md`](../assets/examples/example-4-custom.md). Each "
        "shows (a) the user requirement, (b) the use-case analysis card, and (c) the resulting "
        "prompt. Search here for a pattern similar to your task.".format(paper_link(7, "")),
        worked,
        sources,
    )
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="report stale or missing extracts without writing")
    args = parser.parse_args()
    try:
        outputs = build(PAPER.read_text(encoding="utf-8"))
    except (OSError, PaperError) as exc:
        print("ERROR: " + str(exc), file=sys.stderr)
        return 2
    stale = []
    for relative, content in outputs.items():
        path = SKILL_ROOT / relative
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        stale.append(relative)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if args.check:
        for relative in stale:
            print("STALE: " + relative + " (run scripts/generate-references.py)")
        print("{}: {} generated files checked".format("FAIL" if stale else "PASS", len(outputs)))
        return 1 if stale else 0
    print("Wrote {} of {} generated files.".format(len(stale), len(outputs)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
